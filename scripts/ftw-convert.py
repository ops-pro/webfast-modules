#!/usr/bin/env python3
"""Convert webfast-ngfw's Rust rule tests into go-ftw YAML test files.

The rule tests stay written in Rust; this script reads them and writes the same
tests as YAML in go-ftw's format (2.6.2, the v2-compatible `stages` form that
go-ftw parses with ftw-tests-schema v2.3.0), so the same tests can later run
blackbox: a webfast container, a backend container, a go-ftw container. No test
string is retyped by hand: everything comes out of the sources.

Reads:
  - crates/webfast-ngfw/src/engine.rs: the `takes` and `neighbours` tables of
    `each_cve_rule_takes_its_signature_and_not_its_neighbour`, and the `BROWSER`
    headers of the corpus test;
  - crates/webfast-ngfw/src/detect/corpus.rs: the `SQLI`, `XSS` and `BENIGN`
    arrays, each value sent three ways (a query parameter `v` with spaces as
    `%20` and as `+`, and a cookie `c`), as the engine's test sends them;
  - docs/ngfw-rules.md: every rule's `Number` line, as a cross-check of the
    numbers the script computes the way `rule::number_of` does.

Writes, under crates/webfast-ngfw/tests/ftw/:
  - cve/<rule id>.yaml     one file per cve rule: its take (`expect_ids`, 403)
  - cve/neighbours.yaml    the neighbours: no cve rule (`no_expect_ids`, 200)
  - sqli/942170.yaml       the SQLI corpus x 3 spellings (403, the whole filter)
  - xss/941150.yaml        the XSS corpus x 3 spellings (403, the whole filter)
  - corpus/benign.yaml     the BENIGN corpus x 3 spellings (200, no hit)

Every request is a GET for HTTP/1.1 with `host: www.example.com`, as the
engine's `request()` helper builds it. Corpus values reach the YAML only
percent-encoded (`query_encoded`: the unreserved characters as-is, a space as
`+` or `%20`, the rest as `%XX`), so no control or non-ASCII byte is ever
written raw and every string survives a YAML round trip byte for byte.

Usage:
  python scripts/ftw-convert.py           write the files (idempotent)
  python scripts/ftw-convert.py --check   exit non-zero when they differ from
                                          what the sources give

Payloads are never printed: the script reports counts per file only. It needs
PyYAML (`pip install pyyaml`).

CI: `--check` is the gate, in the spirit of the `the_rules_reference_is_current`
test that keeps docs/ngfw-rules.md current. A workflow step such as

  - name: the go-ftw YAML tests are current
    run: |
      python -m pip install pyyaml
      python scripts/ftw-convert.py --check

fails when a Rust test changed without regenerating the YAML files.
"""

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.stderr.write("PyYAML is required: python -m pip install pyyaml\n")
    sys.exit(2)

ROOT = Path(__file__).resolve().parent.parent
NGFW = ROOT / "crates" / "webfast-ngfw"
ENGINE = NGFW / "src" / "engine.rs"
CORPUS = NGFW / "src" / "detect" / "corpus.rs"
RULES_DOC = ROOT / "docs" / "ngfw-rules.md"
OUT_ROOT = NGFW / "tests" / "ftw"

# The libinjection rules the corpus files are grouped under.
SQLI_RULE = "wf-942-170"
XSS_RULE = "wf-941-150"

DEST_ADDR = "127.0.0.1"
PORT = 80
HOST = ("host", "www.example.com")

GENERATED_BY = (
    "# Generated by scripts/ftw-convert.py from the Rust rule tests: "
    "edit the sources, then regenerate. Do not edit by hand.\n"
)

UNRESERVED = frozenset(
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~"
)


class ConvertError(Exception):
    """A source does not have the shape this script reads."""


# ---------------------------------------------------------------- the sources


class Rust:
    """A small reader of the Rust value grammar the test tables use: string
    literals, tuples and slices, over comments and whitespace."""

    def __init__(self, text, where):
        self.t = text
        self.where = where
        self.i = 0

    def error(self, message):
        line = self.t.count("\n", 0, self.i) + 1
        raise ConvertError(f"{self.where}:{line}: {message}")

    def skip(self):
        """Whitespace and `//` comments."""
        while True:
            while self.i < len(self.t) and self.t[self.i] in " \t\r\n":
                self.i += 1
            if self.t.startswith("//", self.i):
                end = self.t.find("\n", self.i)
                self.i = len(self.t) if end < 0 else end
            else:
                return

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else ""

    def literal(self):
        """A Rust string literal: `"…"` with escapes, or `r#"…"#`."""
        if self.peek() == '"':
            start = self.i
            self.i += 1
            out = []
            while True:
                if self.i >= len(self.t):
                    self.i = start
                    self.error("unterminated string literal")
                c = self.t[self.i]
                if c == '"':
                    self.i += 1
                    return "".join(out)
                if c == "\\":
                    out.append(self.escape())
                else:
                    out.append(c)
                    self.i += 1
        hashes = 0
        if self.peek() == "r":
            j = self.i + 1
            while j < len(self.t) and self.t[j] == "#":
                j += 1
            if j < len(self.t) and self.t[j] == '"':
                hashes = j - self.i - 1
                end_marker = '"' + "#" * hashes
                k = self.t.find(end_marker, j + 1)
                if k < 0:
                    self.i = start = self.i
                    self.error("unterminated raw string literal")
                value = self.t[j + 1 : k]
                self.i = k + len(end_marker)
                return value
        self.error("expected a string literal")

    def escape(self):
        """After a backslash, the escaped character."""
        self.i += 1
        if self.i >= len(self.t):
            self.error("unterminated escape")
        c = self.t[self.i]
        simple = {"n": "\n", "r": "\r", "t": "\t", "\\": "\\", '"': '"', "'": "'", "0": "\0"}
        if c in simple:
            self.i += 1
            return simple[c]
        if c == "x":
            self.i += 1
            return self.hex(2, 0x7F)
        if c == "u":
            self.i += 1
            if self.peek() != "{":
                self.error("expected '{' after \\u")
            self.i += 1
            value = self.hex(6, 0x10FFFF, at_least=1)
            if self.peek() != "}":
                self.error("expected '}' after \\u{…")
            self.i += 1
            return value
        self.error(f"unknown escape: {c!r}")

    def hex(self, width, limit, at_least=None):
        digits = ""
        while len(digits) < width and self.peek() in "0123456789abcdefABCDEF":
            digits += self.t[self.i]
            self.i += 1
        if at_least is None:
            at_least = width
        if len(digits) < at_least:
            self.error("expected hex digits")
        value = int(digits, 16)
        if value > limit:
            self.error("escape out of range")
        return chr(value)

    def value(self):
        """A string literal, a tuple or a (referenced) slice."""
        self.skip()
        c = self.peek()
        if c == "&":
            self.i += 1
            self.skip()
            if self.peek() != "[":
                self.error("expected '[' after '&'")
            return self.list()
        if c == "[":
            return self.list()
        if c == "(":
            return self.tuple()
        if c == '"':
            return self.literal()
        self.error(f"unexpected character: {c!r}")

    def list(self):
        self.i += 1  # '['
        items = []
        self.skip()
        if self.peek() == "]":  # empty, or only a trailing comma left
            self.i += 1
            return items
        while True:
            items.append(self.value())
            self.skip()
            if self.peek() != ",":
                break
            self.i += 1
            self.skip()
            if self.peek() == "]":
                break
        if self.peek() != "]":
            self.error("expected ',' or ']'")
        self.i += 1
        return items

    def tuple(self):
        self.i += 1  # '('
        items = []
        self.skip()
        if self.peek() == ")":
            self.i += 1
            return tuple(items)
        while True:
            items.append(self.value())
            self.skip()
            if self.peek() != ",":
                break
            self.i += 1
            self.skip()
            if self.peek() == ")":
                break
        if self.peek() != ")":
            self.error("expected ',' or ')'")
        self.i += 1
        return tuple(items)


def extract(text, marker, where):
    """The value of the binding that starts with `marker`: a tuple or string
    literal per element of the slice (or array) the marker opens."""
    if text.count(marker) != 1:
        raise ConvertError(f"{where}: expected exactly one `{marker}`, found {text.count(marker)}")
    reader = Rust(text, where)
    reader.i = text.index(marker) + len(marker)
    return reader.list()


def read(path):
    try:
        return path.read_text(encoding="utf-8")
    except OSError as e:
        raise ConvertError(f"cannot read {path.relative_to(ROOT)}: {e}")


def query_encoded(value, plus):
    """As a browser puts a value in a query string (detect.rs `query_encoded`):
    the unreserved characters as-is, a space as `+` or `%20`, the rest `%XX`."""
    out = []
    for b in value.encode("utf-8"):
        c = chr(b)
        if c in UNRESERVED:
            out.append(c)
        elif plus and c == " ":
            out.append("+")
        else:
            out.append("%%%02X" % b)
    return "".join(out)


def number_of(rule_id):
    """The number a rule id stands for (rule.rs `number_of`): `wf-942-190` is
    942190, `wf-cve-2022-22965` is 20220022965."""
    rest = rule_id[3:] if rule_id.startswith("wf-") else None
    if rest is None:
        return None
    if rest.startswith("cve-"):
        parts = rest[len("cve-") :].split("-")
        year, number, suffix = (parts + [None])[:3] if 2 <= len(parts) <= 3 else (None, None, None)
        if year is None or len(year) != 4 or not year.isascii() or not year.isdigit():
            return None
        if not 4 <= len(number) <= 7 or not number.isascii() or not number.isdigit():
            return None
        if suffix is None:
            extra = 0
        elif len(suffix) == 1 and "b" <= suffix <= "j":
            extra = ord(suffix) - ord("a")
        else:
            return None
        return extra * 100_000_000_000 + int(year) * 10_000_000 + int(number)
    section, sep, rule = rest.partition("-")
    if sep and len(section) == 3 and section.isdigit() and len(rule) == 3 and rule.isdigit():
        return int(section + rule)
    return None


def doc_numbers(text):
    """Every rule's `Number` line of docs/ngfw-rules.md, by rule id."""
    import re

    numbers = {}
    headings = list(re.finditer(r"^### (wf-[0-9a-z-]+)[ \t]*$", text, re.M))
    for n, match in enumerate(headings):
        end = headings[n + 1].start() if n + 1 < len(headings) else len(text)
        line = re.search(r"^[-] Number `(\d+)`", text[match.end() : end], re.M)
        if line:
            numbers[match.group(1)] = int(line.group(1))
    return numbers


# ------------------------------------------------------------------ the files


def input_of(uri, headers):
    return {
        "dest_addr": DEST_ADDR,
        "port": PORT,
        "method": "GET",
        "uri": uri,
        "version": "HTTP/1.1",
        "headers": dict(headers),
    }


def output_of(status, log=None):
    out = {"status": status}
    if log is not None:
        out["log"] = log
    return out


def stage_of(uri, headers, status, log=None, description=None):
    stage = {"input": input_of(uri, headers), "output": output_of(status, log)}
    if description is not None:
        stage["description"] = description
    return stage


def file_doc(name, rule_number, description, tests):
    return {
        "meta": {"author": "webfast", "description": description, "enabled": True, "name": name},
        "rule_id": rule_number,
        "tests": tests,
    }


def checked_number(numbers, rule_id):
    number = number_of(rule_id)
    if number is None:
        raise ConvertError(f"{rule_id}: not a rule id this script knows how to number")
    if numbers.get(rule_id) != number:
        raise ConvertError(
            f"{rule_id}: the computed number {number} and docs/ngfw-rules.md disagree "
            f"({numbers.get(rule_id)})"
        )
    return number


def cve_of(rule_id):
    return rule_id[len("wf-cve-") :]


def build():
    """Every output file, as (path relative to the repository root, document)."""
    engine = read(ENGINE)
    corpus = read(CORPUS)
    numbers = doc_numbers(read(RULES_DOC))

    takes = extract(engine, "let takes: &[Case] = &[", "src/engine.rs")
    neighbours = extract(engine, "let neighbours: &[(&str, &[(&str, &str)])] = &[", "src/engine.rs")
    browser = extract(engine, "const BROWSER: [(&str, &str); 2] = [", "src/engine.rs")
    sqli = extract(corpus, "pub(crate) const SQLI: &[&str] = &[", "src/detect/corpus.rs")
    xss = extract(corpus, "pub(crate) const XSS: &[&str] = &[", "src/detect/corpus.rs")
    benign = extract(corpus, "pub(crate) const BENIGN: &[&str] = &[", "src/detect/corpus.rs")

    for name, table in (("takes", takes), ("neighbours", neighbours), ("BROWSER", browser)):
        if not table:
            raise ConvertError(f"src/engine.rs: the {name} table is empty")
    for element in takes:
        if len(element) != 3 or not all(isinstance(v, str) for v in element[:2]):
            raise ConvertError("src/engine.rs: a `takes` entry is not (rule, uri, headers)")
    for element in neighbours:
        if len(element) != 2 or not isinstance(element[0], str):
            raise ConvertError("src/engine.rs: a `neighbours` entry is not (uri, headers)")
    if len(browser) != 2:
        raise ConvertError("src/engine.rs: BROWSER does not have two headers")
    for name, values in (("SQLI", sqli), ("XSS", xss), ("BENIGN", benign)):
        if not values or not all(isinstance(v, str) for v in values):
            raise ConvertError(f"src/detect/corpus.rs: the {name} array is empty or not strings")

    # Every cve rule has a case, as the Rust test asserts.
    doc_cve = {rule for rule in numbers if rule.startswith("wf-cve-")}
    takes_cve = {element[0] for element in takes}
    if doc_cve != takes_cve:
        missing = ", ".join(sorted(doc_cve - takes_cve)) or "none"
        extra = ", ".join(sorted(takes_cve - doc_cve)) or "none"
        raise ConvertError(f"the cve rules and the takes table disagree: missing {missing}, extra {extra}")

    take_numbers = [checked_number(numbers, element[0]) for element in takes]
    no_expect_ids = list(take_numbers)  # the whole cve set, in the sources' order
    files = {}
    rel = lambda *parts: Path(*parts).as_posix()

    for (rule_id, uri, headers), number in zip(takes, take_numbers):
        cve = cve_of(rule_id)
        files[rel("crates", "webfast-ngfw", "tests", "ftw", "cve", f"{rule_id}.yaml")] = file_doc(
            rule_id,
            number,
            f"The cve set's rule for CVE-{cve}: it refuses the request shape of its CVE.",
            [
                {
                    "test_id": 1,
                    "desc": f"The request shape of CVE-{cve} that the rule refuses: "
                    "the marker its signature looks for, not a working exploit.",
                    "stages": [
                        stage_of(uri, [HOST] + list(headers), 403, {"expect_ids": [number]})
                    ],
                }
            ],
        )

    files[rel("crates", "webfast-ngfw", "tests", "ftw", "cve", "neighbours.yaml")] = file_doc(
        "neighbours",
        0,
        "Ordinary requests to the same products and paths as the cve rules' CVEs: "
        "no cve rule may trigger.",
        [
            {
                "test_id": index,
                "desc": f"An ordinary request to the same product or path ({index} of {len(neighbours)}): "
                "no rule of the cve set triggers.",
                "stages": [
                    stage_of(uri, [HOST] + list(headers), 200, {"no_expect_ids": no_expect_ids})
                ],
            }
            for index, (uri, headers) in enumerate(neighbours, start=1)
        ],
    )

    places = (
        ("query parameter, spaces as %20", lambda v: ("/p?v=" + query_encoded(v, False), list(browser))),
        ("query parameter, spaces as + (a form sent by GET)", lambda v: ("/p?v=" + query_encoded(v, True), list(browser))),
        ("cookie", lambda v: ("/p", list(browser) + [("cookie", "c=" + query_encoded(v, False))])),
    )

    def corpus_tests(values, desc):
        return [
            {
                "test_id": index,
                "desc": f"{desc} {index} of {len(values)}",
                "stages": [
                    stage_of(uri, [HOST] + headers, status, description=place)
                    for place, build in places
                    for uri, headers in [build(value)]
                ],
            }
            for index, value in enumerate(values, start=1)
        ]

    corpus_files = (
        (
            rel("crates", "webfast-ngfw", "tests", "ftw", "sqli", f"{checked_number(numbers, SQLI_RULE)}.yaml"),
            SQLI_RULE,
            sqli,
            403,
            "SQL injection payload",
            "The SQL injection corpus of the detectors' evaluation set: the built-in sets "
            "together refuse every payload, in a query (both spellings of a space) and in a cookie.",
        ),
        (
            rel("crates", "webfast-ngfw", "tests", "ftw", "xss", f"{checked_number(numbers, XSS_RULE)}.yaml"),
            XSS_RULE,
            xss,
            403,
            "Cross-site scripting payload",
            "The XSS corpus of the detectors' evaluation set: the built-in sets together refuse "
            "every payload, in a query (both spellings of a space) and in a cookie.",
        ),
        (
            rel("crates", "webfast-ngfw", "tests", "ftw", "corpus", "benign.yaml"),
            None,
            benign,
            200,
            "Benign value",
            "The benign values of the detectors' evaluation set: the whole filter lets each "
            "through, in a query (both spellings of a space) and in a cookie.",
        ),
    )
    for path, rule_id, values, status, desc, meta_description in corpus_files:
        number = checked_number(numbers, rule_id) if rule_id else 0
        name = Path(path).stem
        files[path] = file_doc(name, number, meta_description, corpus_tests(values, desc))

    return files


# --------------------------------------------------------------- write / check


def emit(doc):
    """The file's bytes: a provenance comment, then the document PyYAML writes."""
    text = yaml.dump(doc, sort_keys=False, default_flow_style=False, allow_unicode=True, width=1_000_000)
    return (GENERATED_BY + text).encode("utf-8")


def validate(doc, path):
    """The schema's required fields and types, on what is about to be written."""
    where = f"{path}: "
    if not isinstance(doc, dict) or not {"meta", "rule_id", "tests"} <= doc.keys():
        raise ConvertError(f"{where}missing meta, rule_id or tests")
    if not isinstance(doc["rule_id"], int):
        raise ConvertError(f"{where}rule_id is not an integer")
    for test in doc["tests"]:
        if not isinstance(test, dict) or not {"test_id", "stages"} <= test.keys():
            raise ConvertError(f"{where}a test misses test_id or stages")
        if not isinstance(test["test_id"], int):
            raise ConvertError(f"{where}a test_id is not an integer")
        for stage in test["stages"]:
            if not isinstance(stage, dict) or not {"input", "output"} <= stage.keys():
                raise ConvertError(f"{where}a stage misses input or output")
            for key in ("expect_ids", "no_expect_ids"):
                ids = stage["output"].get("log", {}).get(key)
                if ids is not None and not all(isinstance(n, int) for n in ids):
                    raise ConvertError(f"{where}{key} holds a non-integer")


def check_or_write(files, check):
    existing = (
        {path.relative_to(ROOT).as_posix() for path in OUT_ROOT.rglob("*.yaml")}
        if OUT_ROOT.is_dir()
        else set()
    )
    stale = sorted(set(existing) - set(files))
    differences = []
    tests = stages = 0
    for path in sorted(files):
        doc = files[path]
        validate(doc, path)
        data = emit(doc)
        on_disk = (ROOT / path).read_bytes() if (ROOT / path).exists() else None
        if check:
            if on_disk != data:
                differences.append(path if on_disk is not None else f"{path} (missing)")
        else:
            target = ROOT / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            if yaml.safe_load(data) != doc:
                raise ConvertError(f"{path}: the written file does not read back equal")
        tests += len(doc["tests"])
        stages += sum(len(test["stages"]) for test in doc["tests"])
        print(f"{path}: {len(doc['tests'])} tests, {sum(len(t['stages']) for t in doc['tests'])} stages")
    if not check and stale:
        print("note: files under tests/ftw the sources no longer give: " + ", ".join(stale))
    if check:
        if differences or stale:
            for path in differences:
                print(f"{path}: differs from what the sources give")
            for path in stale:
                print(f"{path}: not from the sources")
            print("regenerate with: python scripts/ftw-convert.py")
            return 1
        print(f"OK: {len(files)} files current ({tests} tests, {stages} stages)")
    else:
        print(f"wrote {len(files)} files: {tests} tests, {stages} stages")
    return 0


def main(argv):
    parser = argparse.ArgumentParser(
        description="Convert the Rust rule tests of webfast-ngfw to go-ftw YAML files."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the YAML files differ from what the sources give",
    )
    args = parser.parse_args(argv)
    try:
        files = build()
        return check_or_write(files, args.check)
    except ConvertError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
